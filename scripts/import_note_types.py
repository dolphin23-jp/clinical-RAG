#!/usr/bin/env python3
"""Import the chart-note types (the field names and their order) from a clinical-modules checkout into web/note-types.js.

  python3 scripts/import_note_types.py --modules ../clinical-modules          # write web/note-types.js
  python3 scripts/import_note_types.py --modules ../clinical-modules --check  # exit 1 if web/note-types.js is out of date

What is taken from each `note-types/*.toml`, and nothing else (docs/enhancement-plan.md 7.3):
  id, title, version, status, kind, primary_axis, variants, and per section: key, label, requirement, variant.
What is NOT taken: `sources` (which common entities a field reads: that belongs to the training repository's renderer),
`implementation`, `existing_output`, and any comment. No clinical content comes across: only names and an order.

The Modules commit the types were read from is recorded in the output, so a later change there can be seen and
re-imported. The output is deterministic (same input, same bytes). Nothing is written without --modules pointing at a
directory that has a note-types/ folder.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "web" / "note-types.js"

TYPE_KEYS = ("id", "title", "version", "status", "kind", "primary_axis")
SECTION_KEYS = ("key", "label", "requirement", "variant")
REQUIREMENTS = {"required", "conditional"}

HEADER = """// Chart-note types: field names, their order and whether a field is required or conditional.
// GENERATED by scripts/import_note_types.py from clinical-modules' note-types/*.toml. Do not edit by hand: re-import.
// Only names and order come across (no `sources`, no clinical content). The repository the types belong to stays training-only;
// this only borrows the shape of a note (docs/enhancement-plan.md 7.3).
"""


def load_types(modules: Path) -> list[dict]:
    folder = modules / "note-types"
    files = sorted(folder.glob("*.toml"))
    if not files:
        raise SystemExit(f"no note-types/*.toml under {modules}")
    out = []
    for f in files:
        with f.open("rb") as fh:
            raw = tomllib.load(fh)
        t = {k: raw[k] for k in TYPE_KEYS if k in raw}
        missing = [k for k in ("id", "title", "version") if k not in t]
        if missing or not raw.get("sections"):
            raise SystemExit(f"{f.name}: needs {', '.join(missing) or 'sections'}")
        if isinstance(raw.get("variants"), list):
            t["variants"] = [str(v) for v in raw["variants"]]
        sections = []
        for s in raw["sections"]:
            sec = {k: s[k] for k in SECTION_KEYS if k in s}
            if not all(k in sec for k in ("key", "label", "requirement")) or sec["requirement"] not in REQUIREMENTS:
                raise SystemExit(f"{f.name}: a section needs key, label and requirement (required|conditional): {s}")
            sections.append(sec)
        keys = [s["key"] for s in sections]
        if len(set(keys)) != len(keys):
            raise SystemExit(f"{f.name}: duplicate section keys")
        t["sections"] = sections
        out.append(t)
    ids = [t["id"] for t in out]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate note type ids")
    return sorted(out, key=lambda t: t["id"])


def modules_commit(modules: Path) -> str:
    try:
        r = subprocess.run(["git", "-C", str(modules), "rev-parse", "--short=12", "HEAD"], capture_output=True, text=True, check=True)
        return r.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def render(types: list[dict], commit: str) -> str:
    source = {"repository": "clinical-modules", "path": "note-types/*.toml", "commit": commit, "count": len(types)}
    by_id = {t["id"]: t for t in types}
    return (
        HEADER
        + "export const NOTE_TYPES_SOURCE = "
        + json.dumps(source, ensure_ascii=False, indent=2)
        + ";\n\nexport const NOTE_TYPES = "
        + json.dumps(by_id, ensure_ascii=False, indent=2)
        + ";\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--modules", required=True, type=Path, help="a clinical-modules checkout (the folder that has note-types/)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--commit", default=None, help="record this commit instead of asking git (for a checkout without .git)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the output file differs")
    a = ap.parse_args(argv)
    types = load_types(a.modules)
    text = render(types, a.commit if a.commit is not None else modules_commit(a.modules))
    if a.check:
        same = a.out.exists() and a.out.read_text(encoding="utf-8") == text
        print(("up to date: " if same else "OUT OF DATE: ") + str(a.out))
        return 0 if same else 1
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out} ({len(types)} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
