// Builds worker/src/extract-catalog.ts: the questions of each flow as the extraction (/api/extract) needs them, from the structure already
// imported into web/flow-schema.js (docs/enhancement-plan.md 8.15).  Only the questions that are facts (web/extract-model.js `extractable`: not
// a judgment, a plan, a disposition or a case field), and only what the model must see and what validates its answer: the question id, its
// label, its type, the unit, the options (id, label) and the exclusive ones.  No rule, differential, help text or bridge classification (those
// stay on the screen's side: web/extract-model.js reads the schema itself).
//
//   node scripts/build_extract_catalog.mjs            writes the file
//   node scripts/build_extract_catalog.mjs --check    exits 1 when the file is not what the schema gives now
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { extractable } from "../web/extract-model.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(ROOT, "worker", "src", "extract-catalog.ts");

const plain = (s) => String(s).replace(/^★\d+\s*/, "").trim();

/** { source, flows: { [id]: { id, title, questions } } } from the imported schema. */
export function buildCatalog(FLOWS, source) {
  const flows = {};
  for (const f of Object.values(FLOWS)) {
    const questions = [];
    for (const q of f.questions) {
      if (!extractable(q)) continue; // facts only: no judgment, plan or disposition is offered to the model (web/extract-model.js)
      const o = { id: q.id, label: plain(q.label), type: q.type };
      if (q.unit) o.unit = q.unit;
      if (q.options?.length) o.options = q.options.map((x) => [x.id, plain(x.label)]);
      if (q.exclusive?.length) o.exclusive = [...q.exclusive];
      questions.push(o);
    }
    flows[f.id] = { id: f.id, title: f.title, questions };
  }
  return { source: { commit: source.commit, flows: Object.keys(flows).length }, flows };
}

/** The text of the generated module. */
export function render(catalog) {
  const lines = Object.values(catalog.flows).map((f) => `  ${JSON.stringify(f.id)}: ${JSON.stringify(f)},`);
  return [
    "// The questions of each flow, for the extraction (worker/src/extract.ts).",
    "// GENERATED by scripts/build_extract_catalog.mjs from web/flow-schema.js (which scripts/import_flow_schema.py imports from clinical-modules).",
    "// Do not edit by hand: re-run the script (it has --check; worker/test/extract.test.ts runs the same comparison).",
    "// Structure only: no rule, differential, help text or card text (docs/clinical-use.md 1e).",
    "",
    "export interface CatalogQuestion {",
    "  id: string;",
    '  label: string;',
    '  type: "choice" | "multi" | "number" | "time" | "text";',
    "  unit?: string;",
    "  options?: [string, string][];",
    "  exclusive?: string[];",
    "}",
    "export interface CatalogFlow {",
    "  id: string;",
    "  title: string;",
    "  questions: CatalogQuestion[];",
    "}",
    `export const CATALOG_SOURCE = ${JSON.stringify(catalog.source)};`,
    "export const CATALOG: Record<string, CatalogFlow> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

export async function generate() {
  const m = await import(pathToFileURL(join(ROOT, "web", "flow-schema.js")).href);
  return render(buildCatalog(m.FLOWS, m.FLOW_SCHEMA_SOURCE));
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(OUT, "utf-8");
    } catch {
      /* missing */
    }
    if (cur !== text) {
      console.error("worker/src/extract-catalog.ts is out of date: run node scripts/build_extract_catalog.mjs");
      process.exit(1);
    }
    console.log("extract catalog is up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${text.length} chars)`);
  }
}
