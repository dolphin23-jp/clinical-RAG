#!/usr/bin/env python3
"""Import the question structure of clinical-modules' dialogue flows into web/flow-schema.js.

  python3 scripts/import_flow_schema.py --modules ../clinical-modules          # write web/flow-schema.js
  python3 scripts/import_flow_schema.py --modules ../clinical-modules --check  # exit 1 if web/flow-schema.js is out of date

The doctor's decision (2026-10-24, docs/clinical-use.md 1e): the structure only, never the training repository's clinical
judgement.  What is taken from each `flows/*.toml`:
  flow:      scene, module, version, the title (from the file's first comment line), the phases (id, name, short, frames),
             the question that starts the time axis (origin_q, origin_label)
  question:  id, frame (slot), label, type, unit, options (id, label, short), core, required, exclusive, when, line,
             and from the flow's `bridge` declaration the structure of the question: its kind (ent), the time question it hangs
             on (at), the option ids that mean none / unable / waiting / pending / unknown (neg, unable, wait, pend, unk, val)
  defs:      only the named conditions that a question's `when` uses (and what those use): a visibility condition on answers
and from each `scenes/*.md`: the frames (number, name, purposes P1-P5).
What is NOT taken: `[[rule]]` `[[ddx]]` `[[axis]]` `[[fact]]` `[[mark]]` (the judgement), `help` (clinical prose and links to cards), the phase
`hint` text, questions of type `axis`, the bridge's prose (`concept`, `why`) and its other keys, `[[result]]` declarations, and any
other text of the repository.
No patient information is involved: this is a one-way copy of structure from a repository that holds only invented cases.

The Modules commit the schema was read from is recorded in the output.  The output is deterministic (same input, same bytes).
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "web" / "flow-schema.js"

SUPPORTED_TYPES = {"choice", "multi", "number", "text", "time"}
QUESTION_KEYS = ("id", "slot", "label", "type", "unit", "core", "required", "exclusive", "when", "line")
# what is taken from a question's entry in the flow's `bridge` (structure only; `concept` and `why` are prose and are left)
BRIDGE_SCALARS = ("ent", "at", "of", "phase", "status")
# the values the bridge's scalars may take (what the Modules flows use today); anything else is refused, so prose cannot come across
BRIDGE_ENUMS = {
    "ent": {"observation", "context", "assessment", "action", "time", "condition", "reason", "none"},
    "status": {"performed", "planned"},
    "phase": {"trigger", "initial", "reassessment"},
}
ORIGIN_LABEL_MAX = 20
BRIDGE_LISTS = ("neg", "unable", "wait", "pend", "unk", "val")
HEADER = """// Question structure of clinical-modules' dialogue flows: which questions a scene x symptom asks, in which phase, with which options.
// GENERATED by scripts/import_flow_schema.py from clinical-modules' flows/*.toml and scenes/*.md. Do not edit by hand: re-import.
// Structure only (docs/clinical-use.md 1e): no rules, differentials, axes, help text or card text come across.
// Loaded on demand (import()) because it is large.
"""


def split_option(raw: str) -> dict:
    """"id:label" or "id:label|short" -> {id, label, short?}"""
    oid, _, rest = raw.partition(":")
    label, short = (rest.rsplit("|", 1) + [""])[:2] if "|" in rest else (rest, "")
    out = {"id": oid.strip(), "label": label.strip()}
    if short.strip():
        out["short"] = short.strip()
    return out


def def_refs(expr: str) -> list[str]:
    return re.findall(r"\$([A-Za-z0-9_]+)", expr or "")


def load_flow(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    raw = tomllib.loads(text)
    first = text.splitlines()[0] if text else ""
    m = re.match(r"#\s*(.+?)\s*の対話フロー", first)
    title = m.group(1) if m else f"{raw.get('scene', '')} × {raw.get('module', '')}"
    scene, module = raw.get("scene"), raw.get("module")
    if not scene or not module or not raw.get("question") or not raw.get("phase"):
        raise SystemExit(f"{path.name}: needs scene, module, questions and phases")
    questions, skipped = [], []
    for q in raw["question"]:
        if q.get("type") not in SUPPORTED_TYPES:
            skipped.append(q.get("id"))
            continue
        item = {k: q[k] for k in QUESTION_KEYS if k in q}
        if q.get("options"):
            item["options"] = [split_option(o) for o in q["options"]]
        if q["type"] in ("choice", "multi") and not item.get("options"):
            raise SystemExit(f"{path.name}: question {q.get('id')} has no options")
        questions.append(item)
    ids = [q["id"] for q in questions]
    if len(set(ids)) != len(ids):
        raise SystemExit(f"{path.name}: duplicate question ids")
    bridge = {b.get("q"): b for b in raw.get("bridge", []) if isinstance(b, dict)}
    for q in questions:
        b = bridge.get(q["id"])
        if not b:
            continue
        br = {}
        for k in BRIDGE_SCALARS:
            v = b.get(k)
            if v is None:
                continue
            if not isinstance(v, str):
                raise SystemExit(f"{path.name}: bridge {q['id']}.{k} must be a string")
            if k in BRIDGE_ENUMS and v not in BRIDGE_ENUMS[k]:
                raise SystemExit(f"{path.name}: bridge {q['id']}.{k} = {v!r} is not one of {sorted(BRIDGE_ENUMS[k])}")
            if k in ("at", "of") and v not in ids:
                raise SystemExit(f"{path.name}: bridge {q['id']}.{k} names {v!r}, which is not a question of the flow")
            br[k] = v
        for k in BRIDGE_LISTS:
            if isinstance(b.get(k), list) and b[k]:
                bad = [x for x in b[k] if x not in {o["id"] for o in q.get("options", [])}]
                if bad:
                    raise SystemExit(f"{path.name}: bridge {q['id']}.{k} names options the question does not have: {bad}")
                br[k] = list(b[k])
        if br:
            q["br"] = br
    defs_all = {d["id"]: d["expr"] for d in raw.get("def", []) if "expr" in d}
    need, todo = {}, [r for q in questions for r in def_refs(q.get("when", ""))]
    while todo:
        name = todo.pop()
        if name in need:
            continue
        if name not in defs_all:
            raise SystemExit(f"{path.name}: `when` uses ${name}, which the flow does not define")
        need[name] = defs_all[name]
        todo.extend(def_refs(defs_all[name]))
    phases = [{k: p[k] for k in ("id", "name", "short", "slots") if k in p} for p in raw["phase"]]
    flow = {"id": f"{scene}.{module}", "scene": scene, "module": module, "version": raw.get("version"), "title": title, "phases": phases, "questions": questions}
    if bool(raw.get("origin_q")) != bool(raw.get("origin_label")):
        raise SystemExit(f"{path.name}: origin_q and origin_label go together")
    if raw.get("origin_q"):
        by_id = {q["id"]: q for q in questions}
        if raw["origin_q"] not in by_id or by_id[raw["origin_q"]]["type"] != "time":
            raise SystemExit(f"{path.name}: origin_q {raw['origin_q']} is not a time question of the flow")
        if len(str(raw["origin_label"])) > ORIGIN_LABEL_MAX:
            raise SystemExit(f"{path.name}: origin_label is longer than {ORIGIN_LABEL_MAX} characters")
        flow["origin"] = {"q": raw["origin_q"], "label": raw["origin_label"]}
    if need:
        flow["defs"] = dict(sorted(need.items()))
    if skipped:
        flow["skipped"] = sorted(set(skipped))
    return flow


def load_scene(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.search(r"^scene:\s*(.+)$", text, re.M)
    frames = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and cells[0].isdigit():
            purposes = [p.strip() for p in cells[3].split(",") if re.fullmatch(r"P\d", p.strip())]
            frames.append({"n": int(cells[0]), "name": cells[1], "purposes": purposes})
    return {"id": path.stem, "name": m.group(1).strip() if m else path.stem, "frames": frames}


def load_all(modules: Path) -> tuple[list[dict], list[dict]]:
    flows_dir, scenes_dir = modules / "flows", modules / "scenes"
    files = sorted(flows_dir.glob("*.toml"))
    if not files:
        raise SystemExit(f"no flows/*.toml under {modules}")
    flows = [load_flow(f) for f in files]
    scenes = [load_scene(f) for f in sorted(scenes_dir.glob("*.md"))] if scenes_dir.is_dir() else []
    ids = [f["id"] for f in flows]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate flow ids")
    return sorted(flows, key=lambda f: f["id"]), sorted(scenes, key=lambda s: s["id"])


def modules_commit(modules: Path) -> str:
    try:
        r = subprocess.run(["git", "-C", str(modules), "rev-parse", "--short=12", "HEAD"], capture_output=True, text=True, check=True)
        return r.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def render(flows: list[dict], scenes: list[dict], commit: str) -> str:
    source = {"repository": "clinical-modules", "path": "flows/*.toml, scenes/*.md", "commit": commit, "flows": len(flows), "scenes": len(scenes)}
    dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    lines = [HEADER.rstrip("\n"), "export const FLOW_SCHEMA_SOURCE = " + json.dumps(source, ensure_ascii=False) + ";", "", "export const SCENES = {"]
    lines += [f"  {json.dumps(s['id'])}: {dump(s)}," for s in scenes]
    lines += ["};", "", "export const FLOWS = {"]
    lines += [f"  {json.dumps(f['id'])}: {dump(f)}," for f in flows]
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--modules", required=True, type=Path, help="a clinical-modules checkout (the folder that has flows/)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--commit", default=None, help="record this commit instead of asking git (for a checkout without .git)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the output file differs")
    a = ap.parse_args(argv)
    flows, scenes = load_all(a.modules)
    text = render(flows, scenes, a.commit if a.commit is not None else modules_commit(a.modules))
    if a.check:
        same = a.out.exists() and a.out.read_text(encoding="utf-8") == text
        print(("up to date: " if same else "OUT OF DATE: ") + str(a.out))
        return 0 if same else 1
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out} ({len(flows)} flows, {len(scenes)} scenes, {a.out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
