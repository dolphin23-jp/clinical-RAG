// Builds worker/src/sim-catalog.ts: the questions of the emergency flows as the simulation's AI calls (/api/sim) need them, from the structure
// already imported into web/flow-schema.js (docs/enhancement-plan.md 8.21, step 2).  For each question: id, label, type, unit, options (id,
// label), exclusive ones, and its kind for the simulation: "fact" (the case gives a value), "reading" (the doctor reads or decides: no value),
// "action" (the doctor's act), "time" (a time the screen makes).  "afterAct" marks a fact that only makes sense after an act (its `when` reads an
// action question): it is not in the first state.  No rule, differential, help text or card text.
//
//   node scripts/build_sim_catalog.mjs            writes the file
//   node scripts/build_sim_catalog.mjs --check    exits 1 when the file is not what the schema gives now
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { JUDGMENT_IDS } from "../web/extract-model.js";
import { FACT_ENTS, isReading, whenRefs } from "../web/sim-case.js";
import { isEmergencyFlow, simReadings } from "../web/sim-model.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(ROOT, "worker", "src", "sim-catalog.ts");
const plain = (s) => String(s).replace(/^★(\d+|条件付き)\s*/, "").trim();

export function buildCatalog(FLOWS, source) {
  const readings = simReadings(JUDGMENT_IDS);
  const flows = {};
  for (const f of Object.values(FLOWS)) {
    if (!isEmergencyFlow(f.id)) continue;
    const byId = new Map(f.questions.map((q) => [q.id, q]));
    const questions = [];
    for (const q of f.questions) {
      if (["age", "sex"].includes(q.id)) continue;
      const ent = q.br?.ent;
      const kind = ent === "time" ? "time" : ent === "action" ? "action" : FACT_ENTS.includes(ent) && !isReading(q, readings) ? "fact" : "reading";
      const o = { id: q.id, label: plain(q.label), type: q.type, kind };
      if (q.unit) o.unit = q.unit;
      if (q.options?.length) o.options = q.options.map((x) => [x.id, plain(x.short || x.label)]);
      if (q.exclusive?.length) o.exclusive = [...q.exclusive];
      if (kind === "fact" && whenRefs(q.when).some((r) => byId.get(r)?.br?.ent === "action")) o.afterAct = true;
      questions.push(o);
    }
    flows[f.id] = { id: f.id, title: f.title, questions };
  }
  return { source: { commit: source.commit, flows: Object.keys(flows).length }, flows };
}

export function render(catalog) {
  const lines = Object.values(catalog.flows).map((f) => `  ${JSON.stringify(f.id)}: ${JSON.stringify(f)},`);
  return [
    "// The questions of the emergency flows, for the simulation's AI calls (worker/src/sim.ts).",
    "// GENERATED by scripts/build_sim_catalog.mjs from web/flow-schema.js (which scripts/import_flow_schema.py imports from clinical-modules).",
    "// Do not edit by hand: re-run the script (it has --check; worker/test/simapi.test.ts runs the same comparison).",
    "// Structure only: no rule, differential, help text or card text (docs/clinical-use.md 1e).",
    "",
    "export interface SimQuestion {",
    "  id: string;",
    "  label: string;",
    '  type: "choice" | "multi" | "number" | "time" | "text";',
    '  kind: "fact" | "reading" | "action" | "time";',
    "  unit?: string;",
    "  options?: [string, string][];",
    "  exclusive?: string[];",
    "  afterAct?: boolean;",
    "}",
    "export interface SimFlow {",
    "  id: string;",
    "  title: string;",
    "  questions: SimQuestion[];",
    "}",
    `export const SIM_CATALOG_SOURCE = ${JSON.stringify(catalog.source)};`,
    "export const SIM_CATALOG: Record<string, SimFlow> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

export async function generate() {
  const m = await import(pathToFileURL(join(ROOT, "web", "flow-schema.js")).href);
  return render(buildCatalog(m.FLOWS, m.FLOW_SCHEMA_SOURCE));
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(OUT, "utf-8");
    } catch {
      /* missing */
    }
    if (cur !== text) {
      console.error("worker/src/sim-catalog.ts is out of date: run node scripts/build_sim_catalog.mjs");
      process.exit(1);
    }
    console.log("sim catalog is up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${text.length} chars)`);
  }
}
