def make(files: dict[str, str]) -> Path:
    root = Path(tempfile.mkdtemp(prefix="notetypes-"))
    (root / "note-types").mkdir()
    for name, text in files.items():
        (root / "note-types" / name).write_text(text, encoding="utf-8")
    return root


def js_json(text: str, name: str) -> dict:
    m = re.search(rf"export const {name} = (\{{.*?\n\}});", text, re.S)
    assert m, name
    return json.loads(m.group(1))


class ImportTest(unittest.TestCase):
    def test_only_names_and_order_come_across(self):
        types = imp.load_types(make({"x01.toml": X01, "x02.toml": X02}))
        self.assertEqual([t["id"] for t in types], ["X01", "X02"])
        x01 = types[0]
        self.assertEqual(set(x01), {"id", "title", "version", "status", "kind", "primary_axis", "sections"})
        self.assertEqual([s["key"] for s in x01["sections"]], ["first", "second"])  # the file's order
        for s in x01["sections"]:
            self.assertEqual(set(s), {"key", "label", "requirement"})  # no `sources`
        text = imp.render(types, "abc123")
        for left_out in ("\"sources\"", "patient_context", "implementation", "existing_output", "somewhere.md", "Not for clinical use"):
            self.assertNotIn(left_out, text)

    def test_variants_are_kept_so_a_request_can_be_told_from_a_response(self):
        t = imp.load_types(make({"x02.toml": X02}))[0]
        self.assertEqual(t["variants"], ["request", "response"])
        self.assertEqual([s.get("variant") for s in t["sections"]], ["request", "response"])

    def test_output_is_deterministic_and_records_where_it_came_from(self):
        root = make({"x02.toml": X02, "x01.toml": X01})
        a = imp.render(imp.load_types(root), "f00dfeed")
        b = imp.render(imp.load_types(root), "f00dfeed")
        self.assertEqual(a, b)
        src = js_json(a, "NOTE_TYPES_SOURCE")
        self.assertEqual((src["repository"], src["commit"], src["count"]), ("clinical-modules", "f00dfeed", 2))
        self.assertEqual(list(js_json(a, "NOTE_TYPES")), ["X01", "X02"])  # sorted by id, whatever the file order
        self.assertTrue(a.startswith("// Chart-note types"))
        self.assertIn("GENERATED by scripts/import_note_types.py", a)

    def test_bad_input_is_refused(self):
        bad_requirement = X01.replace('requirement = "required"', 'requirement = "maybe"')
        no_sections = 'id = "X03"\ntitle = "t"\nversion = "1"\n'
        dup_keys = X01.replace('key = "second"', 'key = "first"')
        for name, text in {"requirement": bad_requirement, "sections": no_sections, "duplicate": dup_keys}.items():
            with self.subTest(name), self.assertRaises(SystemExit):
                imp.load_types(make({"x.toml": text}))
        with self.assertRaises(SystemExit):
            imp.load_types(make({"a.toml": X01, "b.toml": X01}))  # the same id twice
        with self.assertRaises(SystemExit):
            imp.load_types(make({}))

    def test_check_mode_writes_nothing_and_reports_staleness(self):
        root = make({"x01.toml": X01})
        out = Path(tempfile.mkdtemp()) / "note-types.js"
        self.assertEqual(imp.main(["--modules", str(root), "--out", str(out), "--commit", "c1"]), 0)
        before = out.read_text(encoding="utf-8")
        self.assertEqual(imp.main(["--modules", str(root), "--out", str(out), "--commit", "c1", "--check"]), 0)
        (root / "note-types" / "x01.toml").write_text(X01.replace("最初の欄", "改名した欄"), encoding="utf-8")
        self.assertEqual(imp.main(["--modules", str(root), "--out", str(out), "--commit", "c1", "--check"]), 1)
        self.assertEqual(out.read_text(encoding="utf-8"), before)  # --check does not rewrite


class CommittedFileTest(unittest.TestCase):
    def test_web_note_types_matches_a_modules_checkout(self):
        committed = (ROOT / "web" / "note-types.js").read_text(encoding="utf-8")
        modules = Path(os.environ.get("MODULES_DIR", str(ROOT.parent / "clinical-modules")))
        if not (modules / "note-types").is_dir():
            self.skipTest("no clinical-modules checkout (set MODULES_DIR)")
        commit = js_json(committed, "NOTE_TYPES_SOURCE")["commit"]
        # compared at the commit the file records, so a later unrelated Modules commit does not matter; a changed type does
        self.assertEqual(imp.render(imp.load_types(modules), commit), committed, "web/note-types.js is out of date: re-run scripts/import_note_types.py")

    def test_committed_file_has_only_names_and_order(self):
        types = js_json((ROOT / "web" / "note-types.js").read_text(encoding="utf-8"), "NOTE_TYPES")
        self.assertGreaterEqual(len(types), 16)
        for t in types.values():
            self.assertLessEqual(set(t), {"id", "title", "version", "status", "kind", "primary_axis", "variants", "sections"})
            for s in t["sections"]:
                self.assertLessEqual(set(s), {"key", "label", "requirement", "variant"})


if __name__ == "__main__":
    unittest.main()
