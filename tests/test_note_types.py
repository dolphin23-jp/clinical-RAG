"""scripts/import_note_types.py: the chart-note types borrowed from clinical-modules (docs/enhancement-plan.md 7.3).

Synthetic type files only. The committed web/note-types.js is also compared with a real clinical-modules checkout when one is
next to this repository (or named by MODULES_DIR); without one, that comparison is skipped.
"""
